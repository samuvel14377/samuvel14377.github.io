-- Run this in Supabase SQL Editor AFTER enabling Anonymous Sign-ins in Auth settings.
create extension if not exists pg_cron;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username ~ '^[A-Za-z0-9_]{3,20}$'),
  nickname text not null check (char_length(nickname) between 2 and 24),
  is_banned boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null,
  nickname text not null,
  content text not null check (char_length(content) between 1 and 500),
  created_at timestamptz not null default now()
);

create index if not exists messages_created_at_idx on public.messages(created_at desc);
create index if not exists messages_user_id_idx on public.messages(user_id);

create or replace function public.is_admin(uid uuid default auth.uid())
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.admin_users where user_id=uid); $$;

create or replace function public.is_banned(uid uuid default auth.uid())
returns boolean language sql stable security definer set search_path=public
as $$ select coalesce((select is_banned from public.profiles where id=uid), false); $$;

create or replace function public.message_is_allowed(body text)
returns boolean language sql immutable
as $$
  select char_length(body) between 1 and 500
  and body !~* '(^|[^a-z])(fuck|fucking|motherfucker|bitch|bastard|asshole|shit|cunt|dick|pussy|whore|slut|nigger|faggot)([^a-z]|$)'
  and body !~* '(\+?[0-9][0-9 ().-]*){8,}'
  and body !~* '[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}'
  and body !~* '\m(whatsapp|telegram|snapchat|instagram)\M\s*[:@]?[[:alnum:]_.-]{3,}';
$$;

alter table public.profiles enable row level security;
alter table public.admin_users enable row level security;
alter table public.messages enable row level security;

-- Profiles: a user can read/update only their own profile; admins can view/manage all.
drop policy if exists "profile read self or admin" on public.profiles;
create policy "profile read self or admin" on public.profiles for select to authenticated
using (id=auth.uid() or public.is_admin());
drop policy if exists "profile insert self" on public.profiles;
create policy "profile insert self" on public.profiles for insert to authenticated
with check (id=auth.uid() and not is_banned);
drop policy if exists "profile update admin only" on public.profiles;
drop policy if exists "profile update self when not banned" on public.profiles;
create policy "profile update self when not banned" on public.profiles for update to authenticated
using (id=auth.uid() and not is_banned) with check (id=auth.uid() and not is_banned);
create policy "profile update admin only" on public.profiles for update to authenticated
using (public.is_admin()) with check (public.is_admin());

-- Admin list can only be read by admins; users cannot grant themselves admin.
drop policy if exists "admin list self/admin" on public.admin_users;
create policy "admin list self/admin" on public.admin_users for select to authenticated
using (user_id=auth.uid() or public.is_admin());

-- All signed-in guests can read chat. Only non-banned users can send clean text.
drop policy if exists "messages visible to authenticated" on public.messages;
create policy "messages visible to authenticated" on public.messages for select to authenticated using (true);
drop policy if exists "send allowed messages" on public.messages;
create policy "send allowed messages" on public.messages for insert to authenticated
with check (user_id=auth.uid() and not public.is_banned(auth.uid()) and public.message_is_allowed(content));
drop policy if exists "admins delete messages" on public.messages;
create policy "admins delete messages" on public.messages for delete to authenticated using (public.is_admin());

-- Prevent guests from changing other people's message metadata.
drop policy if exists "admins update messages" on public.messages;
create policy "admins update messages" on public.messages for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- Turn on realtime for messages (ignore error if already added).
do $$ begin alter publication supabase_realtime add table public.messages; exception when duplicate_object then null; when undefined_object then null; end $$;

-- Optional auto-delete: messages older than 24 hours. Requires pg_cron available in your Supabase project.
-- If this errors because pg_cron is unavailable, set up a scheduled database job in Supabase Dashboard instead.
select cron.schedule('glowchat-delete-expired-messages', '*/15 * * * *', $$delete from public.messages where created_at < now() - interval '24 hours'$$)
on conflict (jobname) do nothing;
